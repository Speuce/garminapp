# ABOUTME: Writes a recording's accelerometer Y-axis samples as a Monkey C test fixture array.
# ABOUTME: Usage: .venv/bin/python tools/fit_fixture.py <recording.fit> <ConstantName> > test/<Name>.mc
import sys

import fitparse


def y_samples(path):
    samples = []
    for message in fitparse.FitFile(path).get_messages("accelerometer_data"):
        samples += [round(v) for v in message.get_value("calibrated_accel_y")]
    return samples


def main():
    path, name = sys.argv[1], sys.argv[2]
    samples = y_samples(path)
    rows = [", ".join(str(s) for s in samples[i:i + 25]) for i in range(0, len(samples), 25)]
    print(f"// ABOUTME: Accelerometer Y-axis samples (milli-g, ~25 Hz) from {path.split('/')[-1]}.")
    print("// ABOUTME: Generated by tools/fit_fixture.py; replayed by RepCounter tests.")
    print("import Toybox.Lang;")
    print()
    print("(:test)")
    print(f"const {name} = [")
    print(",\n".join("    " + r for r in rows))
    print("] as Array<Number>;")


if __name__ == "__main__":
    main()
